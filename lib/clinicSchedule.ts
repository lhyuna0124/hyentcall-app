// 실험실이 아닌 정식 기능입니다. 관리자 화면에서 수정한 내용은 KV에 저장되며,
// 이 값은 최초 1회 기본값으로만 쓰입니다 (/api/clinic-schedule 참고).
function row(id: string, doctorName: string, values: string[], saturdayWeek = "") {
  const days = ["월", "화", "수", "목", "금"];
  const slots: Record<string, string> = {};
  days.forEach((d, i) => {
    slots[`${d}-AM`] = values[i * 2] ?? "";
    slots[`${d}-PM`] = values[i * 2 + 1] ?? "";
  });
  return { id, doctorName, slots, saturdayWeek };
}

